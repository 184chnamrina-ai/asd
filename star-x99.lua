-- Build skin lookup table (Strict Matching)
local ValidSkins = {}

for _, name in ipairs(PoolcueSkins) do
    ValidSkins[string.lower(name)] = "weapon_poolcue"
end

for _, name in ipairs(BottleSkins) do
    ValidSkins[string.lower(name)] = "weapon_bottle"
end

-- Console notification function (F8)
local function Notify(msg)
    print("^3[SKIN SYSTEM]^7 " .. msg)
end

-- Apply skin function
local function ApplySkin(weaponType, skinItemName)
    local serverId = GetPlayerServerId(PlayerId())
    TriggerEvent('wps:set-player-skin', serverId, {
        [weaponType] = skinItemName
    })
end

-- Display all available skins in Console (F8)
local function DisplayAllSkins()
    print("")
    print("^3==================================================^7")
    print("^3       POOLCUE SKINS [ weapon_poolcue ] (" .. #PoolcueSkins .. " skins)       ^7")
    print("^3==================================================^7")
    for i, name in ipairs(PoolcueSkins) do
        print(string.format("^7[%02d] ^2%s^7", i, name))
    end

    print("")
    print("^3==================================================^7")
    print("^3       BOTTLE SKINS [ weapon_bottle ] (" .. #BottleSkins .. " skins)        ^7")
    print("^3==================================================^7")
    for i, name in ipairs(BottleSkins) do
        print(string.format("^7[%02d] ^6%s^7", i, name))
    end

    print("")
    print("^3==================================================^7")
    print("^2Usage in F8: ^7skin <full_skin_name>")
    print("^2Example: ^7skin weapon_poolcue_oni_r OR skin weapon_bottle_celebrity")
    print("^1Type: ^7skin reset ^1to reset all weapon skins^7")
    print("^3==================================================^7")
    print("")
end

-- Command: skin (Usable via F8 Console or Chat)
RegisterCommand('skin', function(source, args, rawCommand)
    local input = args[1]

    -- If no argument provided or typing 'skin list', display all skins in F8
    if not input or input == "" or string.lower(input) == "list" or string.lower(input) == "help" then
        DisplayAllSkins()
        return
    end

    local query = string.lower(input)

    -- Reset skin command
    if query == "reset" or query == "off" or query == "clear" or query == "none" then
        local serverId = GetPlayerServerId(PlayerId())
        TriggerEvent('wps:set-player-skin', serverId, {
            ["weapon_poolcue"] = "",
            ["weapon_bottle"] = ""
        })
        Notify("^1Weapon skins have been reset successfully.^7")
        return
    end

    -- Verify exact full skin name
    local weaponType = ValidSkins[query]

    if weaponType then
        ApplySkin(weaponType, query)
        local typeLabel = (weaponType == "weapon_bottle") and "Bottle" or "Poolcue"
        Notify("Skin applied successfully [^3" .. typeLabel .. "^7]: ^2" .. query .. "^7")
    else
        Notify("^1Skin not found: " .. input .. "^7")
        Notify("Type ^3skin^7 in F8 to view all available skins.")
    end
end, false)
